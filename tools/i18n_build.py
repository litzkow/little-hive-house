"""Writes assets/i18n-pt.js (the Portuguese dictionary the site loads) from tools/i18n/pt-*.json and
tools/i18n/patterns.js. Keys are the English text exactly as assets/i18n.js looks it up (see that file).
Run:  python3 tools/i18n_build.py   (then tools/build.py, so the pages get the new ?v=)"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "i18n"


def norm(s):
    return " ".join(s.split())


def load():
    d = {}
    for f in sorted(SRC.glob("pt-*.json")):
        for k, v in json.loads(f.read_text()).items():
            if v is None or v == "":
                continue
            d[norm(k)] = v
    return d


def main():
    d = load()
    pats = (SRC / "patterns.js").read_text() if (SRC / "patterns.js").exists() else "var PATTERNS = [];"
    js = ("/* Generated by tools/i18n_build.py from tools/i18n/. Edit those, not this. */\n(function () {\n"
          + pats + "\nvar DICT = " + json.dumps(d, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
          + ";\nwindow.LHH_I18N && window.LHH_I18N.load(DICT, PATTERNS);\n})();\n")
    (ROOT / "assets" / "i18n-pt.js").write_text(js)
    print(len(d), "entries,", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
