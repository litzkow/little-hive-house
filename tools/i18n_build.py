"""Writes assets/i18n-<lang>.js (the dictionary the site loads for one language) from tools/i18n/<lang>-*.json and
the language's patterns (tools/i18n/patterns.js for Portuguese, tools/i18n/patterns-<lang>.js for the others).
Keys are the English text exactly as assets/i18n.js looks it up (see that file). A language goes live on the site as
soon as its file exists (tools/build.py LANGS).
Run:  python3 tools/i18n_build.py   (then tools/build.py, so the pages get the new ?v=)"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "i18n"


def norm(s):
    return " ".join(s.split())


def langs():
    return sorted({m.group(1) for f in SRC.glob("*.json") if (m := re.match(r"([a-z]{2,3})-", f.name))})


def load(lang):
    d = {}
    for f in sorted(SRC.glob(f"{lang}-*.json")):
        for k, v in json.loads(f.read_text()).items():
            if v is None or v == "":
                continue
            d[norm(k)] = v
    return d


def main():
    for lang in langs():
        d = load(lang)
        pf = SRC / ("patterns.js" if lang == "pt" else f"patterns-{lang}.js")
        pats = pf.read_text() if pf.exists() else "var PATTERNS = [];"
        js = ("/* Generated by tools/i18n_build.py from tools/i18n/. Edit those, not this. */\n(function () {\n"
              + pats + "\nvar DICT = " + json.dumps(d, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
              + ";\nwindow.LHH_I18N && window.LHH_I18N.load(DICT, PATTERNS);\n})();\n")
        (ROOT / "assets" / f"i18n-{lang}.js").write_text(js)
        print(lang, len(d), "entries,", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
